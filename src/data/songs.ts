let cache: Song[] | null = null;

export function builtinSongs(): Song[] {
  if (!cache) cache = SPECS.map((s) => buildSong({ ...s, source: 'builtin' }));
  return cache;
}

export function builtinSong(id: string): Song | undefined {
  return builtinSongs().find((s) => s.id === id);
}
